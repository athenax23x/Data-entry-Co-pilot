"""Writes web/src/layout.generated.ts: the Paykings steps with, for every column, the record path and input kind.

Sources: preview_tool/paykings_layout.json (steps and column order), merchant_notebook/paykings_map.py (column ->
field), merchant_notebook/fields.py (input kind). tests/test_web_layout.py fails when the file is out of date.

    python tools/gen_layout.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from merchant_notebook import fields, paykings_map as PM          # noqa: E402

OUT = ROOT / "web" / "src" / "layout.generated.ts"
TITLES = ["1. Informasi Bisnis", "2. Informasi Alamat", "3. Informasi Pemenuhan Pesanan", "4. Metrik Penjualan",
          "5. Informasi Bank", "6. MCC dan Pajak Bisnis", "7. Pemilik Bisnis 1", "Catatan"]
KIND = {"yes_no": "yesno", "percentage": "percent"}


def build() -> str:
    layout = json.loads((ROOT / "preview_tool" / "paykings_layout.json").read_text(encoding="utf-8"))
    skipped = PM.SKIPPED_COLUMNS                          # not collected: blank CSV columns, hidden here
    steps = []
    for title, step in zip(TITLES, layout["steps"]):
        items = []
        for col in step["columns"]:
            if col in skipped:
                continue
            spec = PM.COLUMN_TO_SPEC[col]
            path = spec.replace("[]", "[0]")
            items.append({"label": col, "path": path, "kind": KIND.get(fields.FIELD_SPECS[spec], "text"),
                          "sensitive": spec in PM.SENSITIVE_SPECS})
        if items:
            steps.append({"title": title, "fields": items})
    body = json.dumps(steps, indent=2, ensure_ascii=False)
    return ("// Generated by tools/gen_layout.py from preview_tool/paykings_layout.json and paykings_map.py.\n"
            "// Do not edit by hand.\n"
            "export type FieldKind = \"text\" | \"yesno\" | \"percent\";\n"
            "export interface FieldDef { label: string; path: string; kind: FieldKind; sensitive: boolean }\n"
            "export interface StepDef { title: string; fields: FieldDef[] }\n\n"
            f"export const STEPS: StepDef[] = {body};\n")


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
